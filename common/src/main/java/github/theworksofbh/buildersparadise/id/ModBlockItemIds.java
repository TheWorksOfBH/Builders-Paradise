    private static BlockItemId create(Identifier blockId, Identifier itemId) {
        return new BlockItemId(ResourceKey.create(Registries.BLOCK, blockId), ResourceKey.create(Registries.ITEM, itemId));
    }

    private static BlockItemId create(String blockName, String itemName) {
        return create(Identifier.fromNamespaceAndPath(BuildersParadiseConstants.MOD_ID, blockName), Identifier.fromNamespaceAndPath(BuildersParadiseConstants.MOD_ID, itemName));
    }

    private static BlockItemId create(String name) {
        Identifier id = Identifier.fromNamespaceAndPath(BuildersParadiseConstants.MOD_ID, name);
        return create(id, id);
    }
